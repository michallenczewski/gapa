// Most między oknem a procesem głównym: tylko te funkcje są dostępne dla interfejsu.
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const path = require('path');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  chromeColors: (bg, fg, h) => ipcRenderer.send('chrome-colors', { bg, fg, h }),
  sep: path.sep,
  dirname: p => path.dirname(p),
  basename: p => path.basename(p),
  parse: p => path.parse(p),
  fileUrl: p => 'pgf://f/' + encodeURIComponent(p),

  list: (dir, exts) => ipcRenderer.invoke('list', dir, exts),
  exists: p => ipcRenderer.invoke('exists', p),
  resolvePath: p => ipcRenderer.invoke('resolve-path', p),
  trash: paths => ipcRenderer.invoke('trash', paths),
  writeNew: (dir, name, buf) => ipcRenderer.invoke('write-new', dir, name, buf),
  roots: () => ipcRenderer.invoke('roots'),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  watch: dir => ipcRenderer.invoke('watch', dir),
  onDirChanged: cb => ipcRenderer.on('dir-changed', (e, d) => cb(d)),
  onMenu: cb => ipcRenderer.on('menu', (e, a) => cb(a)),
  iconGet: () => ipcRenderer.invoke('icon-get'),
  iconSet: n => ipcRenderer.invoke('icon-set', n),
  fullscreenToggle: () => ipcRenderer.send('fullscreen-toggle'),
  onFullscreen: cb => ipcRenderer.on('fullscreen', (e, v) => cb(v)),

  thumbGet: k => ipcRenderer.invoke('thumb-get', k),
  thumbPut: (k, buf, dims, meta) => ipcRenderer.invoke('thumb-put', k, buf, dims, meta),
  thumbForget: h => ipcRenderer.invoke('thumb-forget', h),
  cacheInfo: () => ipcRenderer.invoke('cache-info'),
  cacheClear: () => ipcRenderer.invoke('cache-clear'),
  cacheChoose: () => ipcRenderer.invoke('cache-choose'),
  cacheLimit: mb => ipcRenderer.invoke('cache-limit', mb),
  cacheReveal: () => ipcRenderer.invoke('cache-reveal'),

  showInFolder: p => ipcRenderer.invoke('show-in-folder', p),
  openDefault: p => ipcRenderer.invoke('open-default', p),
  openEditor: (files, choose) => ipcRenderer.invoke('open-editor', files, choose),
  editorName: () => ipcRenderer.invoke('editor-name'),
  statFiles: paths => ipcRenderer.invoke('stat-files', paths),
  copyTo: (paths, dir) => ipcRenderer.invoke('copy-to', paths, dir),
  libRoots: (roots, exts, force) => ipcRenderer.invoke('lib-roots', roots, exts, force),
  libSearch: (q, exts, names) => ipcRenderer.invoke('lib-search', q, exts, names),
  onLibStatus: cb => ipcRenderer.on('lib-status', (e, s) => cb(s)),
  clipFiles: paths => ipcRenderer.invoke('clip-files', paths),
  clipReadFiles: () => ipcRenderer.invoke('clip-read-files'),
  mem: () => ipcRenderer.invoke('mem'),
  transfer: (paths, dest, mode) => ipcRenderer.invoke('transfer', paths, dest, mode),
  rename: (p, name) => ipcRenderer.invoke('rename', p, name),
  undoTransfer: () => ipcRenderer.invoke('undo-transfer'),
  devOf: paths => ipcRenderer.invoke('dev-of', paths),
  currentDrag: () => ipcRenderer.invoke('current-drag'),
  peekPath: (() => { try { return new URLSearchParams(location.search).get('peek'); } catch (e) { return null; } })(),
  peekMulti: (() => { try { return new URLSearchParams(location.search).get('multi') === '1'; } catch (e) { return false; } })(),
  onPeekOpen: cb => ipcRenderer.on('peek-open', (e, p) => cb(p)),
  onPeekKey: cb => ipcRenderer.on('peek-key', (e, k) => cb(k)),
  onPeekHidden: cb => ipcRenderer.on('peek-hidden', () => cb()),
  peekClose: () => ipcRenderer.send('peek-close'),
  peekGet: () => ipcRenderer.invoke('peek-get'),
  peekSet: v => ipcRenderer.invoke('peek-set', v),
  autostartSet: v => ipcRenderer.invoke('autostart-set', v),
  prepMode: (() => { try { return new URLSearchParams(location.search).get('prep') === '1'; } catch (e) { return false; } })(),
  prepGet: () => ipcRenderer.invoke('prep-get'),
  prepPlan: () => ipcRenderer.invoke('prep-plan'),
  prepStart: raiseMB => ipcRenderer.invoke('prep-start', raiseMB),
  prepPause: v => ipcRenderer.invoke('prep-pause', v),
  prepStop: () => ipcRenderer.invoke('prep-stop'),
  prepNightly: v => ipcRenderer.invoke('prep-nightly', v),
  prepNext: () => ipcRenderer.invoke('prep-next'),
  prepReport: ok => ipcRenderer.invoke('prep-report', ok),
  updateGet: () => ipcRenderer.invoke('update-get'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  onUpdateStatus: cb => ipcRenderer.on('update-status', (e, s) => cb(s)),
  onPrepStatus: cb => ipcRenderer.on('prep-status', (e, s) => cb(s)),
  newWindow: p => ipcRenderer.send('new-window', p),
  startPath: (() => { try { return new URLSearchParams(location.search).get('p'); } catch (e) { return null; } })(),
  dragOut: (files, icon, copy) => ipcRenderer.send('drag-out', files, icon, !!copy),
  osThumb: (p, size) => ipcRenderer.invoke('os-thumb', p, size),
  fileHref: p => require('url').pathToFileURL(p).href,
  pathForFile: f => { try { return webUtils.getPathForFile(f); } catch (e) { return null; } }
});
